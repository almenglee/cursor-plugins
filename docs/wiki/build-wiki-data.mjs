#!/usr/bin/env node
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const mdFiles = readdirSync(dir)
  .filter((f) => f.endsWith(".md"))
  .sort((a, b) => (a === "README.md" ? -1 : b === "README.md" ? 1 : a.localeCompare(b)));

const pages = mdFiles.map((file) => {
  const md = readFileSync(join(dir, file), "utf8");
  const titleMatch = md.match(/^#\s+(.+)$/m);
  const title = titleMatch ? titleMatch[1].replace(/[`*_]/g, "").trim() : file;
  return { id: file, title, md };
});

const out = `// Auto-generated by build-wiki-data.mjs — do not edit by hand.\nwindow.WIKI_PAGES = ${JSON.stringify(pages)};\n`;
writeFileSync(join(dir, "wiki-data.js"), out);
console.log(`Bundled ${pages.length} wiki pages into wiki-data.js (${out.length} bytes)`);
